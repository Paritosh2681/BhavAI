import { formatMoney, MARKET_LABEL, NEGOTIATION_LABEL, type MarketType, type NegotiationStatus } from '@bhavai/shared';

export { formatMoney };

export function modeLabel(mode: string | null | undefined): string {
  return mode === 'GEMINI' ? 'Gemini language layer' : 'Policy engine';
}

export function modeDetail(mode: string | null | undefined): string {
  return mode === 'GEMINI'
    ? 'Language is generated by Gemini after the deterministic decision.'
    : 'Gemini is not configured. Messages use deterministic policy text.';
}

export function marketLabel(market: string | null | undefined): string {
  return MARKET_LABEL[(market ?? 'CROSS_BORDER') as MarketType] ?? String(market ?? '');
}

export function negotiationLabel(status: string | null | undefined): string {
  return NEGOTIATION_LABEL[(status ?? 'OPEN') as NegotiationStatus] ?? String(status ?? '');
}

export function percent(value: number | null | undefined, digits = 1): string {
  if (value === null || value === undefined || !Number.isFinite(value)) return '—';
  return `${new Intl.NumberFormat('en-US', { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(value)}%`;
}

export function compactNumber(value: number | null | undefined): string {
  if (value === null || value === undefined || !Number.isFinite(value)) return '—';
  return new Intl.NumberFormat('en-US', { notation: 'compact', maximumFractionDigits: 1 }).format(value);
}

export function shortId(id: string | null | undefined): string {
  if (!id) return '—';
  return id.length > 10 ? `${id.slice(0, 4)}…${id.slice(-4)}` : id;
}

export function dateTime(iso: string | null | undefined): string {
  if (!iso) return '—';
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat('en-US', {
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  }).format(date);
}

export const formatDateTime = dateTime;

export function dayLabel(iso: string | null | undefined): string {
  if (!iso) return '—';
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric' }).format(date);
}

export function countryLabel(code: string | null | undefined): string {
  if (!code) return '—';
  return code === 'IN' ? 'India' : code;
}

export function countryFlag(code: string | null | undefined): string {
  if (!code || code.length !== 2) return '🌐';
  return code
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}
